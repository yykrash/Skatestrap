"""Generate loader/jni_slots.h: the JNINativeInterface and JNIInvokeInterface slot names, in table order, as
X-macro lists. Run: python -I scripts/gen_jni.py ref/mocktail/third_party/jni/include/jni.h loader/jni_slots.h
OpenJDK's header has a few slots past Android's last one (GetModule, IsVirtualThread); extra tail slots are harmless.
"""
import re
import sys
from pathlib import Path

text = Path(sys.argv[1]).read_text()


def slots(struct):
    body = re.search(r"struct %s \{(.*?)\n\};" % struct, text, re.S).group(1)
    names = []
    for m in re.finditer(r"void \*(reserved\d)\s*;|JNICALL \*(\w+)\)", body):
        names.append(m.group(1) or m.group(2))
    return names


env, vm = slots("JNINativeInterface_"), slots("JNIInvokeInterface_")
assert env[:4] == ["reserved0", "reserved1", "reserved2", "reserved3"] and env[4] == "GetVersion", env[:6]
assert "RegisterNatives" in env and vm[3] == "DestroyJavaVM", vm
lines = ["// GENERATED by scripts/gen_jni.py from jni.h: slot names in table order. Do not edit.", "#pragma once"]
lines.append("#define JNI_ENV_SLOTS(X) \\\n" + " \\\n".join(f"    X({n})" for n in env[4:]))
lines.append("#define JNI_ENV_COUNT %d  // including the 4 reserved slots" % len(env))
lines.append("#define JNI_VM_SLOTS(X) \\\n" + " \\\n".join(f"    X({n})" for n in vm[3:]))
lines.append("#define JNI_VM_COUNT %d" % len(vm))
Path(sys.argv[2]).write_text("\n".join(lines) + "\n")
print(f"env {len(env)} slots, vm {len(vm)} slots -> {sys.argv[2]}")
