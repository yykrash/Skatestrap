"""Generate loader/gen_gl.c: a SysV-callable wrapper for every GLES 3.2 and EGL 1.5 function, each
forwarding to ANGLE's libGLESv2.dll / libEGL.dll (Windows calling convention).

Run: python -I scripts/gen_gl.py dl/khronos/include loader/gen_gl.c
GL and EGL types are fixed-size Khronos types, identical on Android and Windows, so the bodies are pure
pass-through. Functions whose meaning differs (native windows, eglGetProcAddress) are listed in HAND and
left to egl_hand.c.
"""
import re
import sys
from pathlib import Path

HAND = {"eglGetProcAddress", "eglCreateWindowSurface", "eglGetDisplay"}

inc = Path(sys.argv[1])
out = Path(sys.argv[2])
protos = []  # (lib, ret, name, params)
for lib, header, pat in (
    ("gl", inc / "GLES3/gl32.h", r"GL_APICALL\s+(.+?)\s*GL_APIENTRY\s+(\w+)\s*\((.*?)\);"),
    ("egl", inc / "EGL/egl.h", r"EGLAPI\s+(.+?)\s*EGLAPIENTRY\s+(\w+)\s*\((.*?)\);"),
):
    text = re.sub(r"\s+", " ", header.read_text())
    for ret, name, params in re.findall(pat, text):
        if name not in HAND and name not in {p[2] for p in protos}:
            protos.append((lib, ret.strip(), name, params.strip()))


def arg_names(params):
    if params in ("", "void"):
        return []
    names = []
    for p in params.split(","):
        m = re.search(r"(\w+)\s*(\[\s*\w*\s*\])?\s*$", p.strip())
        assert m, p
        names.append(m.group(1))
    return names


lines = [
    "// GENERATED by scripts/gen_gl.py from the Khronos GLES 3.2 / EGL 1.5 headers. Do not edit.",
    "#include <windows.h>",
    "#include <stdio.h>",
    "#include <string.h>",
    "#include <GLES3/gl32.h>",
    "#include <EGL/egl.h>",
    '#include "shim.h"',
    "",
]
for lib, ret, name, params in protos:
    names = arg_names(params)
    plist = "void" if params in ("", "void") else params
    call = ", ".join(names)
    lines.append(f"static {ret} (__stdcall *p_{name})({plist});")
    body = f"p_{name}({call})" if ret == "void" else f"return p_{name}({call})"
    if name == "eglSwapBuffers":  # frame counter (egl_hand.c)
        body = f"void skate_frame(int); skate_frame(0); {ret} r = p_{name}({call}); skate_frame(1); return r"
    lines.append(f"static SYSV {ret} w_{name}({plist}) {{ {body}; }}")
lines.append("")
lines.append("static const struct { const char *name; int egl; void **host; void *wrap; } gl_table[] = {")
for lib, ret, name, params in protos:
    lines.append(f'    {{ "{name}", {1 if lib == "egl" else 0}, (void **)&p_{name}, w_{name} }},')
lines.append("};")
lines.append(r'''
static HMODULE gles, egl;
static void load(void) {
    if (gles) return;
    // ANGLE's DLLs sit next to loader.exe (or on PATH)
    egl = LoadLibraryA("libEGL.dll");
    gles = LoadLibraryA("libGLESv2.dll");
    if (!egl || !gles) { printf("ANGLE not found (libEGL.dll / libGLESv2.dll)\n"); return; }
    for (size_t i = 0; i < sizeof gl_table / sizeof gl_table[0]; i++)
        *gl_table[i].host = (void *)GetProcAddress(gl_table[i].egl ? egl : gles, gl_table[i].name);
}

// The SysV wrapper for a GL/EGL function, or 0. Wrappers whose host function is missing are not handed out.
void *shim_lookup_gl(const char *name) {
    for (size_t i = 0; i < sizeof gl_table / sizeof gl_table[0]; i++)
        if (!strcmp(gl_table[i].name, name)) {
            load();
            if (!*gl_table[i].host) { printf("GL function %s missing in ANGLE\n", name); return 0; }
            return gl_table[i].wrap;
        }
    return 0;
}

// Host (Windows-convention) entry of an EGL function, for the hand-written ones in egl_hand.c.
void *shim_gl_host(const char *name) {
    load();
    return (void *)GetProcAddress(strncmp(name, "egl", 3) ? gles : egl, name);
}
''')
out.write_text("\n".join(lines))
print(f"{len(protos)} wrappers -> {out}")
