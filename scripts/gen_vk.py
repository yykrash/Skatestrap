"""Generate loader/gen_vk.c: a SysV-callable wrapper for every function in vulkan_core.h, forwarding to the
host Vulkan driver (Windows calling convention).

Run: python -I scripts/gen_vk.py dl/khronos/include loader/gen_vk.c
Vulkan struct layouts are identical on x86_64 Android and Windows and no function takes a struct by value, so
bodies are pure pass-through. pAllocator is forced to NULL (its callbacks would be SysV code called with the
MS ABI). Functions with Android meaning live in vk_hand.c (HAND). Debug-callback functions are left out: their
callbacks would be SysV too, and vk_hand.c hides those extensions.
"""
import re
import sys
from pathlib import Path

HAND = {"vkGetInstanceProcAddr", "vkGetDeviceProcAddr", "vkEnumerateInstanceExtensionProperties",
        "vkEnumerateInstanceLayerProperties", "vkCreateInstance", "vkCreateSwapchainKHR",
        "vkAcquireNextImageKHR", "vkQueuePresentKHR", "vkGetPhysicalDeviceSurfacePresentModesKHR"}
SKIP = re.compile(r"DebugReport|DebugUtilsMessenger|SubmitDebugUtilsMessage")

inc = Path(sys.argv[1])
out = Path(sys.argv[2])
text = re.sub(r"\s+", " ", (inc / "vulkan/vulkan_core.h").read_text())
protos = []
for ret, name, params in re.findall(r"VKAPI_ATTR\s+(.+?)\s+VKAPI_CALL\s+(\w+)\s*\((.*?)\);", text):
    if name not in HAND and not SKIP.search(name) and name not in {p[1] for p in protos}:
        protos.append((ret.strip(), name, params.strip()))


def arg_names(params):
    if params in ("", "void"):
        return []
    names = []
    for p in params.split(","):
        m = re.search(r"(\w+)\s*(\[\s*\w*\s*\])?\s*$", p.strip())
        assert m, p
        names.append(m.group(1))
    return names


lines = [
    "// GENERATED by scripts/gen_vk.py from the Khronos vulkan_core.h. Do not edit.",
    "#define VK_NO_PROTOTYPES",
    "#include <string.h>",
    "#include <vulkan/vulkan_core.h>",
    '#include "shim.h"',
    "",
]
for ret, name, params in protos:
    names = arg_names(params)
    plist = "void" if params in ("", "void") else params
    call = ", ".join("0" if n == "pAllocator" else n for n in names)
    lines.append(f"static {ret} (VKAPI_PTR *p_{name})({plist});")
    body = f"p_{name}({call})" if ret == "void" else f"return p_{name}({call})"
    lines.append(f"static SYSV {ret} w_{name}({plist}) {{ {body}; }}")
lines.append("")
lines.append("static const struct { const char *name; void **host; void *wrap; } vk_table[] = {")
for ret, name, params in protos:
    lines.append(f'    {{ "{name}", (void **)&p_{name}, w_{name} }},')
lines.append("};")
lines.append(r'''
// Bind a host entry to its wrapper and hand the wrapper out; 0 for names we don't wrap.
// shortcut: one host pointer per name (latest lookup wins), assumes one live VkInstance/VkDevice; per-handle dispatch if Roblox ever uses two.
void *vk_gen_bind(const char *name, void *host) {
    if (!host) return 0;
    for (size_t i = 0; i < sizeof vk_table / sizeof vk_table[0]; i++)
        if (!strcmp(vk_table[i].name, name)) { *vk_table[i].host = host; return vk_table[i].wrap; }
    return 0;
}
''')
out.write_text("\n".join(lines))
print(f"{len(protos)} wrappers -> {out}")
